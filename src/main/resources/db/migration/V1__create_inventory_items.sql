
CREATE TABLE inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    sku VARCHAR(30) NOT NULL UNIQUE,
    quantity INTEGER NOT NULL,
    price NUMERIC(12, 2) NOT NULL,
    category VARCHAR(20) NOT NULL,
    location VARCHAR(40),
    description VARCHAR(500),

    CONSTRAINT chk_inventory_items_name_length
        CHECK (char_length(name) BETWEEN 3 AND 50),

    CONSTRAINT chk_inventory_items_sku_format
        CHECK (sku ~ '^[A-Za-z0-9_-]+$'),

    CONSTRAINT chk_inventory_items_quantity
        CHECK (quantity >= 0),

    CONSTRAINT chk_inventory_items_price
        CHECK (price >= 0),

    CONSTRAINT chk_inventory_items_category
        CHECK (category IN (
            'ELECTRONICS',
            'FURNITURE',
            'GROCERY',
            'CLOTHING'
        ))
);
